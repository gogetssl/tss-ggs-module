// Builds icons.css: Material Design Icons as SVG (CSS masks) instead of the icon font.
// usage: node gen-icons.js <mdi package dir> <repo modules dir> <output css>
const fs = require('fs');
const path = require('path');

const [mdiDir, modulesDir, outFile] = process.argv.slice(2);
const meta = JSON.parse(fs.readFileSync(path.join(mdiDir, 'meta.json'), 'utf8'));
const byName = new Map(meta.map(m => [m.name, m]));
const byCode = new Map(meta.map(m => [m.codepoint.toUpperCase(), m.name]));
for (const m of meta) for (const a of m.aliases || []) if (!byName.has(a)) byName.set(a, m);

const SKIP_DIRS = new Set(['vendor', 'node_modules', '.git', 'fonts', 'img', 'Samples_disable']);
const EXT = /\.(php|html|js|tpl|yml|yaml|css|vue)$/i;
const files = [];
(function walk(dir) {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
        const p = path.join(dir, e.name);
        if (e.isDirectory()) { if (!SKIP_DIRS.has(e.name)) walk(p); }
        else if (EXT.test(e.name) && !/materialdesignicons|icons\.css$/.test(e.name)) files.push(p);
    }
})(modulesDir);

// 1) icon names used in the sources: mdi-NAME classes and quoted strings that are icon names
const used = new Set();
for (const f of files) {
    const s = fs.readFileSync(f, 'utf8');
    for (const m of s.matchAll(/mdi-([a-z0-9]+(?:-[a-z0-9]+)*)/g)) if (byName.has(m[1])) used.add(m[1]);
    // bare names (setIcon('cog'), Card::tile('check', ...), ICONS maps, menu yml): only on lines that deal with icons
    if (/\.(php|yml|yaml)$/i.test(f)) {
        // hyphenated names anywhere (arrow-right, timer-sand ...)
        for (const m of s.matchAll(/['"]([a-z][a-z0-9]*(?:-[a-z0-9]+)+)['"]/g)) if (byName.has(m[1])) used.add(m[1]);
        let inMap = false;
        for (const line of s.split('\n')) {
            if (/const\s+[A-Z_]*(ICON|STAGE|TONE)/.test(line)) inMap = true;
            const keep = inMap || /icon|tile\(|status\(|::row\(|button\(|foot\(|start\(|kpi_/i.test(line);
            if (inMap && /\];/.test(line)) inMap = false;
            if (!keep) continue;
            for (const m of line.matchAll(/['"]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['"]/g)) if (byName.has(m[1])) used.add(m[1]);
        }
    }
}

// 2) CSS rules that print an MDI codepoint (framework styles: checkboxes, selects, alerts ...)
const cpRules = [];
for (const f of files.filter(f => f.endsWith('.css'))) {
    const s = fs.readFileSync(f, 'utf8');
    for (const m of s.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
        const body = m[2];
        const cp = body.match(/content\s*:\s*["']\\([0-9a-fA-F]{4,5})["']/);
        if (!cp) continue;
        const name = byCode.get(cp[1].toUpperCase().padStart(5, '0'));
        if (!name) continue;
        const sel = m[1].trim().replace(/^.*@media[^{]*$/s, '').trim();
        if (!sel || sel.startsWith('@')) continue;
        cpRules.push({ sel, name, hasDisplay: /(^|;)\s*display\s*:/.test(body), hasSize: /(^|;)\s*(width|height)\s*:/.test(body), file: path.basename(f) });
        used.add(name);
    }
}

function svgUrl(name) {
    const svg = fs.readFileSync(path.join(mdiDir, 'svg', byName.get(name).name + '.svg'), 'utf8')
        .replace(/<\?xml[^>]*>/, '').replace(/\s+/g, ' ').trim()
        .replace(/"/g, "'").replace(/%/g, '%25').replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E');
    return `url("data:image/svg+xml,${svg}")`;
}

let css = `/*
 * Icons as SVG (generated by gen-icons.js from @mdi/svg 7.4.47, Apache 2.0): no icon font is loaded.
 * Every .mdi / .mdi-NAME element draws its SVG through a CSS mask in the current text colour, 1em square, so the
 * existing sizes and colours keep working. Framework rules that printed a font codepoint get the same treatment.
 * Regenerate after adding an icon name that does not appear in the sources yet.
 */
.mdi::before, [class^="mdi-"]::before, [class*=" mdi-"]::before {
    content: "" !important;
    display: inline-block;
    width: 1em;
    height: 1em;
    font-family: inherit !important;
    background-color: var(--mdi-bg, transparent);
    -webkit-mask: var(--mdi-svg, none) center / contain no-repeat;
    mask: var(--mdi-svg, none) center / contain no-repeat;
    vertical-align: -0.125em;
}
.mdi-spin::before { animation: mdi-spin 2s infinite linear; }
@keyframes mdi-spin { from { transform: rotate(0deg); } to { transform: rotate(359deg); } }
`;
const names = [...used].sort();
for (const n of names) css += `.mdi-${n} { --mdi-bg: currentColor; --mdi-svg: ${svgUrl(n)}; }\n`;
css += `\n/* framework rules that printed a font codepoint */\n`;
for (const r of cpRules) {
    css += `${r.sel} { content: "" !important; font-family: inherit !important; background-color: currentColor; -webkit-mask: ${svgUrl(r.name)} center / contain no-repeat; mask: ${svgUrl(r.name)} center / contain no-repeat;`
        + (r.hasDisplay ? '' : ' display: inline-block;') + (r.hasSize ? '' : ' width: 1em; height: 1em;') + ' }\n';
}
fs.writeFileSync(outFile, css);
console.log(`files ${files.length}, icons ${names.length}, codepoint rules ${cpRules.length}, ${Math.round(css.length / 1024)} KB`);
console.log('codepoint rules by file:', JSON.stringify(cpRules.reduce((a, r) => (a[r.file] = (a[r.file] || 0) + 1, a), {})));
